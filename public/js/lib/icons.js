/** Brand mark: signal bars drawn as a dot matrix (columns of 1–4 dots, bottom-aligned). */
export function brandMark(size = 18) {
  let dots = '';
  for (let c = 0; c < 4; c++) for (let r = 0; r <= c; r++) dots += `<circle cx="${4 + c * 4}" cy="${16 - r * 4}" r="1.55"/>`;
  return raw(`<svg width="${size}" height="${size}" viewBox="0 0 20 20" fill="currentColor" aria-hidden="true">${dots}</svg>`);
}

